/**
 * The CI gate's decision and report-validation logic.
 *
 * These are unit tests over the pure functions, so every CI outcome is enforced on
 * every `npm test` run without needing PostgreSQL. The JUnit samples below are shaped
 * as Node's built-in junit reporter emits them; the "all skipped" fixture mirrors a
 * real capture from this repository's suite with TEST_DATABASE_URL unset, which is the
 * case the old grep guard failed to detect.
 */

/** Build a report object directly, for decision-only tests. */
function report(counts: Partial<Counts> = {}, wellFormed = true): JunitReport {
  return {
    wellFormed,
    counts: { ...EMPTY_COUNTS, ...counts },
    problem: wellFormed ? null : "fixture problem",
  };
}

const HEALTHY = { hasDatabaseUrl: true, childExitCode: 0, reportReadable: true };

describe("parseJunit — accepts well-formed reports", () => {
  test("counts passing test cases", () => {
    const xml = `<testsuites><testcase name="a"/><testcase name="b"/></testsuites>`;
    const parsed = parseJunit(xml);
    assert.equal(parsed.wellFormed, true);
    assert.deepEqual(parsed.counts, { testcases: 2, skipped: 0, failures: 0, errors: 0 });
  });

  test("counts skipped, failure and error elements", () => {
    const xml = `<testsuites>
      <testcase name="a"><skipped type="skipped" message="true"/></testcase>
      <testcase name="b"><failure message="boom"/></testcase>
      <testcase name="c"><error message="bad"/></testcase>
    </testsuites>`;
    const parsed = parseJunit(xml);
    assert.equal(parsed.wellFormed, true);
    assert.deepEqual(parsed.counts, { testcases: 3, skipped: 1, failures: 1, errors: 1 });
  });

  test("accepts an XML declaration and system-out sections", () => {
    const xml = `<?xml version="1.0" encoding="utf-8"?>
    <testsuites><testsuite name="s"><testcase name="a"/>
      <system-out>hello</system-out>
    </testsuite></testsuites>`;
    assert.equal(parseJunit(xml).wellFormed, true);
  });

  test("accepts an empty but well-formed root", () => {
    const parsed = parseJunit("<testsuites></testsuites>");
    assert.equal(parsed.wellFormed, true);
    assert.equal(parsed.counts.testcases, 0);
  });
});

describe("parseJunit — accepts everything Node's junit reporter really emits", () => {
  test("accepts a raw '>' inside an attribute value", () => {
    // Captured from Node 22: a suite named "outer & <suite>" is encoded with the '>'
    // left raw. A `<[^>]*>` scan truncates that tag; a structural parser does not.
    const xml = `<testsuites>
      <testsuite name="outer &amp; &lt;suite>" tests="1" failures="0">
        <testcase name="a" classname="test"/>
      </testsuite>
    </testsuites>`;
    const parsed = parseJunit(xml);
    assert.equal(parsed.wellFormed, true, `unexpected rejection: ${parsed.problem}`);
    assert.equal(parsed.counts.testcases, 1);
  });

  test("accepts nested testsuites with mixed testcases", () => {
    const xml = `<testsuites>
      <testsuite name="outer">
        <testsuite name="inner"><testcase name="deep"/></testsuite>
        <testcase name="flat"/>
      </testsuite>
      <testcase name="skipped suite"><skipped type="skipped" message="true"/></testcase>
    </testsuites>`;
    const parsed = parseJunit(xml);
    assert.equal(parsed.wellFormed, true, `unexpected rejection: ${parsed.problem}`);
    assert.deepEqual(parsed.counts, { testcases: 3, skipped: 1, failures: 0, errors: 0 });
  });

  test("accepts XML declaration, comments, whitespace and system-out", () => {
    const xml = `<?xml version="1.0" encoding="utf-8"?>
    <!-- generated by the junit reporter -->
    <testsuites>
      <testsuite name="s">
        <testcase name="a"/>
        <system-out>hello &amp; goodbye</system-out>
      </testsuite>
      <!-- tests 1 -->
    </testsuites>`;
    assert.equal(parseJunit(xml).wellFormed, true);
  });

  test("accepts self-closing tags with whitespace before the slash", () => {
    // XML 1.0: EmptyElemTag ::= '<' Name (S Attribute)* S? '/>'  -- the slash and '>' are
    // adjacent, but whitespace is allowed before the slash.
    assert.equal(parseJunit(`<testsuites><testcase name="a" /></testsuites>`).wellFormed, true);
    assert.equal(parseJunit(`<testsuites><testcase name="a"/></testsuites>`).wellFormed, true);
    assert.equal(parseJunit(`<testsuites><testcase name="a"\t/></testsuites>`).wellFormed, true);
  });

  test("accepts numeric character references and CDATA in text", () => {
    const xml = `<testsuites><testsuite name="s"><testcase name="a &#65; &#x42;"/>` +
      `<system-out><![CDATA[raw < > & text]]></system-out></testsuite></testsuites>`;
    assert.equal(parseJunit(xml).wellFormed, true);
  });

  test("accepts an empty but well-formed root", () => {
    const parsed = parseJunit("<testsuites></testsuites>");
    assert.equal(parsed.wellFormed, true);
    assert.equal(parsed.counts.testcases, 0);
  });
});

