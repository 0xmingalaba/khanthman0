describe("XML 1.0 well-formedness — forbidden character references", () => {
  /**
   * The `Char` production excludes NUL, the surrogate range, 0xFFFE/0xFFFF and all C0
   * controls except tab/CR/LF. A numeric reference to any of those is not well-formed,
   * even though JavaScript's String.fromCodePoint would happily build it.
   */
  const FORBIDDEN: Array<[string, string]> = [
    ["zero (&#0;)", "&#0;"],
    ["zero hex (&#x0;)", "&#x0;"],
    ["C0 control &#1;", "&#1;"],
    ["C0 control &#31;", "&#31;"],
    ["surrogate low &#xD800;", "&#xD800;"],
    ["surrogate high &#xDFFF;", "&#xDFFF;"],
    ["non-character &#xFFFE;", "&#xFFFE;"],
    ["non-character &#xFFFF;", "&#xFFFF;"],
    ["above Unicode &#x110000;", "&#x110000;"],
    ["absurd &#xFFFFFFFF;", "&#xFFFFFFFF;"],
  ];

  for (const [name, ref] of FORBIDDEN) {
    test(`rejects character reference ${name}`, () => {
      const inAttribute = parseJunit(
        `<testsuites><testcase name="a ${ref}"/></testsuites>`
      );
      assert.equal(inAttribute.wellFormed, false, `accepted in attribute: ${name}`);
      assert.match(inAttribute.problem!, /not a legal XML character|out of range/i);
      assert.equal(
        decide({ ...HEALTHY, report: inAttribute }).exitCode,
        EXIT.UNREADABLE_REPORT
      );

      // The same reference in character data must be rejected too.
      const inText = parseJunit(
        `<testsuites><testsuite name="s"><system-out>${ref}</system-out></testsuite></testsuites>`
      );
      assert.equal(inText.wellFormed, false, `accepted in text: ${name}`);
    });
  }

  test("accepts legal references: tab, newline, printable and astral", () => {
    const xml =
      `<testsuites><testcase name="a &#9; &#10; &#x20; &#x1F600;"/></testsuites>`;
    assert.equal(parseJunit(xml).wellFormed, true);
  });

  test("rejects a raw NUL byte in the document", () => {
    const parsed = parseJunit(`<testsuites><testcase name="a\u0000b"/></testsuites>`);
    assert.equal(parsed.wellFormed, false);
    assert.match(parsed.problem!, /not a legal XML character/i);
  });

  test("rejects a raw lone surrogate character", () => {
    const parsed = parseJunit(`<testsuites><testcase name="a\uD800b"/></testsuites>`);
    assert.equal(parsed.wellFormed, false);
  });
});

describe("XML 1.0 well-formedness — comments and character data", () => {
  test("rejects a comment ending in a hyphen before the delimiter", () => {
    const parsed = parseJunit(`<testsuites><!-- foo ---><testcase name="a"/></testsuites>`);
    assert.equal(parsed.wellFormed, false);
    assert.match(parsed.problem!, /comment/i);
    assert.equal(decide({ ...HEALTHY, report: parsed }).exitCode, EXIT.UNREADABLE_REPORT);
  });

  test("rejects a comment containing a double hyphen", () => {
    const parsed = parseJunit(`<testsuites><!-- a -- b --><testcase name="a"/></testsuites>`);
    assert.equal(parsed.wellFormed, false);
    assert.match(parsed.problem!, /"--"/);
  });

  test("rejects an unterminated comment", () => {
    const parsed = parseJunit(`<testsuites><!-- oops <testcase name="a"/></testsuites>`);
    assert.equal(parsed.wellFormed, false);
  });

  test("accepts a comment with a single trailing-ish hyphen not adjacent to the end", () => {
    const xml = `<testsuites><!-- a - b --><testcase name="a"/></testsuites>`;
    assert.equal(parseJunit(xml).wellFormed, true);
  });

  test("rejects a raw ]]> in ordinary character data", () => {
    const parsed = parseJunit(
      `<testsuites><testsuite name="s"><system-out>x ]]> y</system-out></testsuite></testsuites>`
    );
    assert.equal(parsed.wellFormed, false);
    assert.match(parsed.problem!, /\]\]>/);
    assert.equal(decide({ ...HEALTHY, report: parsed }).exitCode, EXIT.UNREADABLE_REPORT);
  });

  test("accepts < and > and & inside a CDATA section", () => {
    // A CDATA section may contain raw markup characters. It may NOT contain `]]>`,
    // because that sequence terminates it -- which is exactly what the previous test
    // asserts is rejected when it appears outside one.
    const xml =
      `<testsuites><testsuite name="s"><system-out><![CDATA[a < b > c & d]]></system-out></testsuite></testsuites>`;
    assert.equal(parseJunit(xml).wellFormed, true);
  });

  test("treats the first ]]> in a CDATA section as its terminator", () => {
    // `]]>` cannot be escaped inside CDATA, so text after it is ordinary character data
    // and a second `]]>` there is invalid. This pins the real XML rule.
    const xml =
      `<testsuites><testsuite name="s"><system-out><![CDATA[x ]]> y]]></system-out></testsuite></testsuites>`;
    const parsed = parseJunit(xml);
    assert.equal(parsed.wellFormed, false);
    assert.match(parsed.problem!, /\]\]>/);
  });

  test("still accepts a raw > in character data and in attribute values", () => {
    const xml = `<testsuites><testsuite name="a > b"><system-out>x > y</system-out></testsuite></testsuites>`;
    assert.equal(parseJunit(xml).wellFormed, true);
  });
});

